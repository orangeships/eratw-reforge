const LIFECYCLE_BY_ID = new Map(
  TFLAG_FIELD_REGISTRY.map((field) => [field.id, field.lifecycle] as const),
);

export function tflagLifecycle(id: number): TflagLifecycle {
  return LIFECYCLE_BY_ID.get(id) ?? "turn";
}

export function createTurnContext(
  selectCom?: number,
  prevCom?: number,
): TurnContext {
  return {
    tflags: {},
    ...(selectCom !== undefined ? { selectCom } : {}),
    ...(prevCom !== undefined ? { prevCom } : {}),
    result: [],
    locals: [],
  };
}

/** Seed the authoritative per-command kojo frame after a resolver opens its turn context. */
export function beginKojoExecutionFrame(
  state: GameState,
  actor: number,
  target: number,
  commandNo: number,
): KojoExecutionFrame {
  const previousCommandNo = state.turnContext?.prevCom;
  const baseBeforeByChara: Record<number, { stamina: number; will: number }> = {};
  for (const slot of [state.master, ...Object.values(state.charas)]) {
    baseBeforeByChara[slot.charaNum] = {
      stamina: slot.state.BASE[BASE_ID.体力] ?? 0,
      will: slot.state.BASE[BASE_ID.気力] ?? 0,
    };
  }
  const frame: KojoExecutionFrame = {
    actor,
    target,
    participants: [...new Set([actor, target])],
    commandNo,
    ...(previousCommandNo === undefined ? {} : { previousCommandNo }),
    elapsedMinutes: 0,
    sourceCheckTimeApplied: false,
    baseBeforeByChara,
    fatigueAppliedByChara: {},
    sourceByChara: {},
    nowExByChara: {},
    args: [],
    results: [],
    roleAliases: { MASTER: 0, PLAYER: 0, TARGET: target },
    doubleMessageBlockedByChara: {},
    counterFiredByChara: {},
    trainingMarkCupsByChara: {},
  };
  state.turnContext ??= createTurnContext(commandNo, previousCommandNo);
  state.turnContext.frame = frame;
  return frame;
}

/** Snapshot a produced SOURCE map before SOURCE_CHECK consumes it. */
export function snapshotKojoSource(
  state: GameState,
  charaNum: number,
  source: Readonly<Record<number, number>>,
): void {
  const frame = state.turnContext?.frame;
  if (!frame) return;
  frame.sourceByChara[charaNum] = { ...source };
}

export function getTflag(state: Readonly<GameState>, id: number): number {
  if (tflagLifecycle(id) === "turn") {
    return state.turnContext
      ? (state.turnContext.tflags[id] ?? 0)
      : (state.tflagStore?.[id] ?? 0);
  }
  return state.tflagStore?.[id] ?? 0;
}

export function setTflag(state: GameState, id: number, value: number): void {
  if (tflagLifecycle(id) === "turn") {
    state.turnContext ??= createTurnContext();
    state.turnContext.tflags[id] = value;
    if (state.tflagStore) delete state.tflagStore[id];
    return;
  }
  state.tflagStore ??= {};
  state.tflagStore[id] = value;
}

export function clearTflag(state: GameState, id: number): void {
  if (state.turnContext) delete state.turnContext.tflags[id];
  if (state.tflagStore) delete state.tflagStore[id];
}

export function addTflag(state: GameState, id: number, delta: number): number {
  const value = getTflag(state, id) + delta;
  setTflag(state, id, value);
  return value;
}

export function setTflagBit(state: GameState, id: number, bit: number): number {
  const value = getTflag(state, id) | (1 << bit);
  setTflag(state, id, value);
  return value;
}

export function clearTflagsByLifecycle(
  state: GameState,
  lifecycle: TflagLifecycle,
): void {
  for (const field of TFLAG_FIELD_REGISTRY) {
    if (field.lifecycle === lifecycle) clearTflag(state, field.id);
  }
}

export function beginTurnContext(
  state: Readonly<GameState>,
  selectCom: number,
): GameState {
  const turnContext = createTurnContext(selectCom, state.turnContext?.selectCom);
  // USERCOM opens the action-selection phase before it probes/executes a
  // command. Keep the phase marker in the authoritative turn context so
  // handlers can distinguish a real command turn from an arbitrary state
  // mutation or a stale continuation.
  turnContext.tflags[TFLAG_ID.调教中COMABLE管理] = 1;
  return {
    ...state,
    turnContext,
  } as GameState;
}

/** Whether the current state represents USERCOM's action-selection phase.
 *  A state without an open turn context is a legacy/menu snapshot and is
 *  treated as selectable for read-only availability probes. Once a turn
 *  context exists, the explicit TFLAG:100 value is authoritative. */
export function isCommandActionPhase(state: Readonly<GameState>): boolean {
  if (!state.turnContext) return true;
  return getTflag(state, TFLAG_ID.调教中COMABLE管理) !== 0;
}

export function clearTurnContext(state: GameState): void {
  state.turnContext = undefined;
}
