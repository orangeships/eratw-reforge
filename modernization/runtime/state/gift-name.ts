function normalizeCharacters(value: string): string {
  return CHARACTER_REPLACEMENTS.reduce((current, [from, to]) => current.replaceAll(from, to), value);
}

/** Localize one upstream atom without changing its catalog identity. */
export function localizeGiftDisplayName(value: string): string {
  const exact = EXACT_LOCALIZATION[value] ?? value;
  if (exact.endsWith("的的")) return normalizeCharacters(exact.slice(0, -1));
  if (exact.endsWith("的な") || exact.endsWith("的の")) {
    return normalizeCharacters(`${exact.slice(0, -2)}的`);
  }
  if (exact.endsWith("の") || exact.endsWith("な")) {
    return normalizeCharacters(`${exact.slice(0, -1)}的`);
  }
  return normalizeCharacters(exact);
}
